test "DOS header validation - valid magic" {
    var mz_data = [_]u8{0} ** 512;
    mz_data[0] = 0x4D; // M
    mz_data[1] = 0x5A; // Z

    const dos: *const win.IMAGE_DOS_HEADER = @ptrCast(@alignCast(&mz_data));
    try std.testing.expect(dos.e_magic == 0x5A4D);
}

test "DOS header from test PE" {
    const dos: *const win.IMAGE_DOS_HEADER = @ptrCast(@alignCast(&RAW_DATA));
    try std.testing.expectEqual(@as(c_ushort, 0x5A4D), dos.e_magic);
    const e_lfanew: usize = @intCast(dos.e_lfanew);
    try std.testing.expect(e_lfanew > 0 and e_lfanew < RAW_DATA.len);
    const pe_sig = std.mem.readInt(u32, RAW_DATA[e_lfanew..][0..4], .little);
    try std.testing.expectEqual(@as(u32, 0x00004550), pe_sig);
}

