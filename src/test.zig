test "ordinal flag detection PE32 vs PE32+" {
    const ordinal_flag_32: u32 = 0x80000000;
    const thunk32: u32 = ordinal_flag_32 | 42;
    try std.testing.expect(thunk32 & ordinal_flag_32 != 0);
    try std.testing.expectEqual(@as(u32, 42), thunk32 & 0xFFFF);

    const ordinal_flag_64: u64 = 0x8000000000000000;
    const thunk64: u64 = ordinal_flag_64 | 100;
    try std.testing.expect(thunk64 & ordinal_flag_64 != 0);
    try std.testing.expectEqual(@as(u64, 100), thunk64 & 0xFFFF);

    const name_thunk32: u32 = 0x00001234;
    try std.testing.expect(name_thunk32 & ordinal_flag_32 == 0);
    const name_thunk64: u64 = 0x00001234;
    try std.testing.expect(name_thunk64 & ordinal_flag_64 == 0);
}

